import Foundation

/// Which Wazuh agent capabilities ("scans") to enable.
struct ScanOptions: Equatable {
    var fim = true              // File integrity monitoring (syscheck)
    var fimRealtime = true      // Real-time FIM (Linux / Windows; macOS is scheduled only)
    var fimReportChanges = true // Store diffs of changed text files in config dirs
    var registry = true         // Windows registry monitoring
    var rootcheck = true        // Rootkit / malware / anomaly detection
    var sca = true              // Security Configuration Assessment (CIS benchmarks)
    var inventory = true        // Syscollector: system inventory (feeds vulnerability detection)
    var logs = true             // Security-relevant log collection
    var osquery = false         // Requires osquery installed on the endpoint
    var docker = false          // Linux only, requires Docker + python docker module
}

enum AgentOS: String, CaseIterable, Identifiable {
    case macOS = "Darwin", linux = "Linux", windows = "Windows"
    var id: String { rawValue }
    var label: String { self == .macOS ? "macOS" : rawValue }
}

/// Generates Wazuh agent configuration. The XML is validated with `verify-agent-conf` before being pushed.
enum AgentConfig {

    /// Centralized config for a group: one `<agent_config os="…">` block per OS.
    static func agentConf(_ o: ScanOptions) -> String {
        var s = "<!-- Generated by Wazuh for macOS: enable all scans -->\n"
        for os in AgentOS.allCases {
            s += "<agent_config os=\"\(os.rawValue)\">\n\(block(os, o, centralized: true).indented(2))</agent_config>\n\n"
        }
        return s
    }

    /// Block to append to one agent's local ossec.conf.
    static func localConf(_ os: AgentOS, _ o: ScanOptions) -> String {
        "<!-- Wazuh for macOS: enable all scans -->\n<ossec_config>\n\(block(os, o).indented(2))</ossec_config>\n"
    }

    /// Adapted CIS macOS benchmark distributed through the group's shared folder (see AgentServer).
    static let macSCAPolicyFile = "cis_apple_macOS_latest.yml"

    static func block(_ os: AgentOS, _ o: ScanOptions, centralized: Bool = false) -> String {
        var x = ""
        if o.fim { x += syscheck(os, o) }
        if o.rootcheck { x += rootcheck(os) }
        if o.sca {
            // Wazuh 4.14 has CIS benchmarks only up to macOS 15; newer macOS gets the adapted copy.
            let mac = (os == .macOS && centralized)
                ? "\n  <policies>\n    <policy>etc/shared/\(macSCAPolicyFile)</policy>\n  </policies>" : ""
            x += """
            <sca>
              <enabled>yes</enabled>
              <scan_on_start>yes</scan_on_start>
              <interval>12h</interval>
              <skip_nfs>yes</skip_nfs>\(mac)
            </sca>

            """
        }
        if o.inventory { x += syscollector(os) }
        if o.logs { x += logs(os) }
        if o.osquery {
            x += """
            <wodle name="osquery">
              <disabled>no</disabled>
              <run_daemon>yes</run_daemon>
              <add_labels>yes</add_labels>
            </wodle>

            """
        }
        if o.docker && os == .linux {
            x += """
            <wodle name="docker-listener">
              <disabled>no</disabled>
              <interval>10m</interval>
              <attempts>5</attempts>
              <run_on_start>yes</run_on_start>
            </wodle>

            """
        }
        return x.isEmpty ? "<!-- no modules selected -->\n" : x
    }

    // MARK: Modules

    private static func syscheck(_ os: AgentOS, _ o: ScanOptions) -> String {
        let rt = (o.fimRealtime && os != .macOS) ? " realtime=\"yes\"" : ""
        let rc = o.fimReportChanges ? " report_changes=\"yes\"" : ""
        var d: [String] = []
        var extra: [String] = []
        let freq: Int
        switch os {
        case .macOS:
            freq = 1800  // macOS agents have no real-time FIM: scan every 30 min
            d = [
                "<directories check_all=\"yes\"\(rc)>/private/etc,/usr/local/etc</directories>",
                "<directories check_all=\"yes\">/bin,/sbin,/usr/bin,/usr/sbin,/usr/local/bin,/opt/homebrew/bin</directories>",
                "<directories check_all=\"yes\">/Library/LaunchAgents,/Library/LaunchDaemons,/Library/StartupItems</directories>",
                "<directories check_all=\"yes\">/Users/*/Library/LaunchAgents</directories>",
                "<directories check_all=\"yes\" recursion_level=\"1\">/Applications</directories>",
                "<directories check_all=\"yes\" recursion_level=\"2\">/Users/*/Downloads</directories>",
            ]
            extra = ["<nodiff>/private/etc/master.passwd</nodiff>",
                     "<ignore>/private/etc/random-seed</ignore>",
                     "<ignore type=\"sregex\">.DS_Store$</ignore>"]
        case .linux:
            freq = 3600
            d = [
                "<directories check_all=\"yes\"\(rt)\(rc)>/etc</directories>",
                "<directories check_all=\"yes\"\(rt)>/usr/bin,/usr/sbin,/bin,/sbin,/boot</directories>",
                "<directories check_all=\"yes\"\(rt)>/var/spool/cron,/root/.ssh</directories>",
                "<directories check_all=\"yes\"\(rt)>/home/*/.ssh</directories>",
            ]
            extra = ["<nodiff>/etc/shadow</nodiff>", "<nodiff>/etc/gshadow</nodiff>",
                     "<nodiff>/etc/ssl/private.key</nodiff>",
                     "<ignore>/etc/mtab</ignore>", "<ignore>/etc/hosts.deny</ignore>",
                     "<ignore>/etc/mail/statistics</ignore>", "<ignore>/etc/random-seed</ignore>",
                     "<ignore>/etc/random.seed</ignore>", "<ignore>/etc/adjtime</ignore>",
                     "<ignore>/etc/httpd/logs</ignore>", "<ignore>/etc/utmpx</ignore>",
                     "<ignore>/etc/wtmpx</ignore>", "<ignore>/etc/cups/certs</ignore>",
                     "<ignore>/etc/dumpdates</ignore>", "<ignore>/etc/svc/volatile</ignore>"]
        case .windows:
            freq = 3600
            d = [
                "<directories check_all=\"yes\"\(rt)\(rc)>%WINDIR%\\System32\\drivers\\etc</directories>",
                "<directories check_all=\"yes\"\(rt)>%WINDIR%\\System32\\Tasks</directories>",
                "<directories check_all=\"yes\"\(rt)>%PROGRAMDATA%\\Microsoft\\Windows\\Start Menu\\Programs\\Startup</directories>",
                "<directories check_all=\"yes\"\(rt)>C:\\Users\\*\\AppData\\Roaming\\Microsoft\\Windows\\Start Menu\\Programs\\Startup</directories>",
                "<directories check_all=\"yes\"\(rt) recursion_level=\"2\">C:\\Users\\*\\Downloads</directories>",
                "<directories check_all=\"yes\" recursion_level=\"1\">C:\\Program Files,C:\\Program Files (x86)</directories>",
            ]
            if o.registry {
                extra = [
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\Software\\Microsoft\\Windows\\CurrentVersion\\Run</windows_registry>",
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\Software\\Microsoft\\Windows\\CurrentVersion\\RunOnce</windows_registry>",
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\Software\\Microsoft\\Windows\\CurrentVersion\\Policies</windows_registry>",
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\Software\\Microsoft\\Windows NT\\CurrentVersion\\Winlogon</windows_registry>",
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\System\\CurrentControlSet\\Services</windows_registry>",
                    "<windows_registry arch=\"both\">HKEY_LOCAL_MACHINE\\Security</windows_registry>",
                ]
            }
        }
        return """
        <syscheck>
          <disabled>no</disabled>
          <frequency>\(freq)</frequency>
          <scan_on_start>yes</scan_on_start>
          <alert_new_files>yes</alert_new_files>
        \((d + extra).map { "  " + $0 }.joined(separator: "\n"))
        </syscheck>

        """
    }

    private static func rootcheck(_ os: AgentOS) -> String {
        if os == .windows {
            return """
            <rootcheck>
              <disabled>no</disabled>
              <frequency>43200</frequency>
            </rootcheck>

            """
        }
        return """
        <rootcheck>
          <disabled>no</disabled>
          <check_files>yes</check_files>
          <check_trojans>yes</check_trojans>
          <check_dev>yes</check_dev>
          <check_sys>yes</check_sys>
          <check_pids>yes</check_pids>
          <check_ports>yes</check_ports>
          <check_if>yes</check_if>
          <frequency>43200</frequency>
          <rootkit_files>etc/shared/rootkit_files.txt</rootkit_files>
          <rootkit_trojans>etc/shared/rootkit_trojans.txt</rootkit_trojans>
          <skip_nfs>yes</skip_nfs>
        </rootcheck>

        """
    }

    private static func syscollector(_ os: AgentOS) -> String {
        """
        <wodle name="syscollector">
          <disabled>no</disabled>
          <interval>1h</interval>
          <scan_on_start>yes</scan_on_start>
          <hardware>yes</hardware>
          <os>yes</os>
          <network>yes</network>
          <packages>yes</packages>
          <ports all="yes">yes</ports>
          <processes>yes</processes>
          <users>yes</users>
          <groups>yes</groups>
          <services>yes</services>
          <browser_extensions>yes</browser_extensions>\(os == .windows ? "\n  <hotfixes>yes</hotfixes>" : "")
        </wodle>

        """
    }

    private static func logs(_ os: AgentOS) -> String {
        switch os {
        case .macOS:
            // The unified-log (macos) collector is already in the agent's default ossec.conf.
            return """
            <localfile>
              <log_format>syslog</log_format>
              <location>/var/log/install.log</location>
            </localfile>

            """
        case .linux:
            return """
            <localfile>
              <log_format>journald</log_format>
              <location>journald</location>
            </localfile>
            <localfile>
              <log_format>audit</log_format>
              <location>/var/log/audit/audit.log</location>
            </localfile>
            <localfile>
              <log_format>syslog</log_format>
              <location>/var/log/auth.log</location>
            </localfile>
            <localfile>
              <log_format>syslog</log_format>
              <location>/var/log/secure</location>
            </localfile>
            <localfile>
              <log_format>syslog</log_format>
              <location>/var/log/dpkg.log</location>
            </localfile>

            """
        case .windows:
            let channels = ["System", "Application",
                            "Microsoft-Windows-Sysmon/Operational",
                            "Microsoft-Windows-Windows Defender/Operational",
                            "Microsoft-Windows-PowerShell/Operational",
                            "Microsoft-Windows-TaskScheduler/Operational",
                            "Microsoft-Windows-Windows Firewall With Advanced Security/Firewall"]
            return channels.map {
                "<localfile>\n  <location>\($0)</location>\n  <log_format>eventchannel</log_format>\n</localfile>\n"
            }.joined() + "\n"
        }
    }
}

extension String {
    func indented(_ n: Int) -> String {
        let pad = String(repeating: " ", count: n)
        return split(separator: "\n", omittingEmptySubsequences: false)
            .map { $0.isEmpty ? "" : pad + $0 }.joined(separator: "\n")
    }
}
